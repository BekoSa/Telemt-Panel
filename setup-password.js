#!/usr/bin/env node
'use strict';
const bcrypt = require('bcryptjs');
const crypto = require('crypto');

const [,, cmd, arg] = process.argv;

if (cmd === 'hash') {
  if (!arg) {
    console.error('Usage: node setup-password.js hash <your-password>');
    process.exit(1);
  }
  const hash = bcrypt.hashSync(arg, 12);
  console.log('\n✓ bcrypt hash generated (rounds=12)');
  console.log('\nAdd to your .env file:\n');
  console.log('  PANEL_PASSWORD_HASH=' + hash);
  console.log();
} else if (cmd === 'secret') {
  const secret = crypto.randomBytes(48).toString('hex');
  console.log('\n✓ Random SESSION_SECRET generated');
  console.log('\nAdd to your .env file:\n');
  console.log('  SESSION_SECRET=' + secret);
  console.log();
} else if (cmd === 'init') {
  // Full interactive setup
  const readline = require('readline');
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  const q = (prompt) => new Promise(res => rl.question(prompt, res));

  (async () => {
    console.log('\n  Telemt Control Panel — Initial Setup\n');

    const username = await q('  Panel username [admin]: ') || 'admin';
    const password = await q('  Panel password: ');
    if (!password) { console.error('Password cannot be empty'); process.exit(1); }

    const telemtUrl   = await q('  Telemt API URL [http://127.0.0.1:9091]: ') || 'http://127.0.0.1:9091';
    const telemtToken = await q('  Telemt API auth token (leave blank if none): ');
    const port        = await q('  Panel port [3000]: ') || '3000';
    rl.close();

    const hash   = bcrypt.hashSync(password, 12);
    const secret = crypto.randomBytes(48).toString('hex');

    const env = [
      '# Telemt Control Panel — generated by setup-password.js',
      '',
      `PANEL_USERNAME=${username}`,
      `PANEL_PASSWORD_HASH=${hash}`,
      '',
      `TELEMT_API_URL=${telemtUrl}`,
      telemtToken ? `TELEMT_API_TOKEN=${telemtToken}` : '# TELEMT_API_TOKEN=',
      '',
      `SESSION_SECRET=${secret}`,
      `SESSION_MAX_AGE_HOURS=8`,
      `PORT=${port}`,
      '',
      '# Set to true if running behind nginx/caddy with HTTPS',
      '# NODE_ENV=production',
      '# TRUST_PROXY=true',
    ].join('\n');

    const fs = require('fs');
    fs.writeFileSync('.env', env + '\n');
    console.log('\n  ✓ .env file written');
    console.log('  ✓ Run: npm start\n');
  })();
} else {
  console.log(`
  Usage:
    node setup-password.js init              — interactive setup wizard (writes .env)
    node setup-password.js hash <password>   — generate bcrypt hash
    node setup-password.js secret            — generate SESSION_SECRET
`);
}
